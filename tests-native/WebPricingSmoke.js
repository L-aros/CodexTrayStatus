'use strict';
const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict'),path=require('node:path');
const source=fs.readFileSync(path.join(__dirname,'../native/Statistics/app.js'),'utf8');
const start=source.indexOf('function renderPricingStatus()'),end=source.indexOf('function render()',start);
assert.ok(start>=0&&end>start);
const target={textContent:''};
Object.defineProperty(target,'innerHTML',{set(){throw new Error('Pricing metadata must render as text');}});
const context={Date,document:{getElementById(){return target;}}};
vm.createContext(context);
vm.runInContext('const $=id=>document.getElementById(id);'+source.match(/const stamp = [^\n]+/)[0]+'let data=null,connected=true;'+source.slice(start,end),context);
vm.runInContext(`data={Pricing:{Available:true,Stale:false,EffectiveDate:'2026-10-31',FetchedAt:1793404800000,ModelCount:2,RejectedModelCount:1}};renderPricingStatus();`,context);
assert.match(target.textContent,/自动费率已读取.*2026-10-31.*上次成功.*可用模型 2 个/);
assert.match(target.textContent,/已忽略 1 条不可用价格/);
vm.runInContext('data.Pricing.Stale=true;data.Pricing.ErrorCode="fetch_failed";renderPricingStatus();',context);
assert.match(target.textContent,/保留上次缓存/);
assert.doesNotMatch(target.textContent,/fetch_failed/);
vm.runInContext('data.Pricing={Available:false,ErrorCode:"invalid_schema"};renderPricingStatus();',context);
assert.match(target.textContent,/尚无可用远程费率.*内置费率/);
assert.doesNotMatch(target.textContent,/invalid_schema/);
vm.runInContext('data.Pricing={Available:true,Source:"Models.dev",EffectiveDate:null,FetchedAt:1793404800000,ModelCount:20};renderPricingStatus();',context);
assert.match(target.textContent,/来源：Models.dev/);
assert.doesNotMatch(target.textContent,/数据日期|未知/,'A feed without a publication date must not invent an effective date');
vm.runInContext('connected=false;renderPricingStatus();',context);
assert.match(target.textContent,/连接中断.*上次费率状态/);
vm.runInContext(`connected=true;data.Pricing={Available:true,EffectiveDate:'<img src=x onerror=alert(1)>',FetchedAt:1793404800000,ModelCount:1};renderPricingStatus();`,context);
assert.match(target.textContent,/<img src=x onerror=alert\(1\)>/);
const page=fs.readFileSync(path.join(__dirname,'../native/Statistics/index.html'),'utf8');
assert.match(page,/id="pricing-source-status"/);
assert.match(page,/https:\/\/models\.dev\//);
assert.match(page,/https:\/\/developers\.openai\.com\/api\/docs\/pricing/);
assert.match(page,/清除手动覆盖/);
console.log('Remote pricing status display tests passed.');
