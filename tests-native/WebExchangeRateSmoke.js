'use strict';
const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict'),path=require('node:path');
const source=fs.readFileSync(path.join(__dirname,'../native/Statistics/app.js'),'utf8');
const page=fs.readFileSync(path.join(__dirname,'../native/Statistics/index.html'),'utf8');
const elements=new Map();
const $=id=>{
  if(!elements.has(id)){
    const element={value:'',checked:false,disabled:false,textContent:''};
    Object.defineProperty(element,'innerHTML',{set(){throw new Error('Exchange-rate metadata must render as text');}});
    elements.set(id,element);
  }
  return elements.get(id);
};
const context={$,Date,preferences:{Currency:'CNY',ExchangeRate:6.6483,AutoExchangeRate:true},data:{ExchangeRate:{Available:true,Rate:6.6483,AsOf:'2026-11-02',FetchedAt:1793404800000,Source:'ECB'}},connected:true,
  settingsDirty:false,formBaseline:null,reminderChecks:{},minutesToTime:()=>'',fillTaskbarWindows(){},readReminderSettings:()=>({})};
vm.createContext(context);
vm.runInContext(source.match(/const stamp = [^\n]+/)[0]+source.slice(source.indexOf('function renderExchangeRateStatus()'),source.indexOf('function render()')),context);
vm.runInContext('renderExchangeRateStatus()',context);
assert.match($('exchange-source-status').textContent,/自动在线汇率.*6\.6483.*参考日期 2026-11-02.*来源：ECB/);
assert.match($('fx-caption').textContent,/在线参考汇率 · 2026-11-02/);
vm.runInContext('data.ExchangeRate.Stale=true;data.ExchangeRate.ErrorCode="fetch_failed";renderExchangeRateStatus()',context);
assert.match($('exchange-source-status').textContent,/保留上次缓存/);
assert.match($('fx-caption').textContent,/在线缓存/);
assert.doesNotMatch($('exchange-source-status').textContent,/fetch_failed/);
vm.runInContext('data.ExchangeRate={Available:false,ErrorCode:"bad_response"};renderExchangeRateStatus()',context);
assert.match($('exchange-source-status').textContent,/尚无可用在线汇率.*已保存的参考值/);
assert.match($('fx-caption').textContent,/在线暂不可用，参考值/);
vm.runInContext('preferences.AutoExchangeRate=false;renderExchangeRateStatus()',context);
assert.match($('fx-caption').textContent,/手动参考汇率/);
vm.runInContext('connected=false;renderExchangeRateStatus()',context);
assert.match($('exchange-source-status').textContent,/连接中断.*上次汇率状态/);
assert.match($('fx-caption').textContent,/连接中断/);
vm.runInContext('connected=true;data.ExchangeRate={Available:true,Rate:6.6,AsOf:"<img src=x>",Source:"<script>bad</script>"};renderExchangeRateStatus()',context);
assert.match($('exchange-source-status').textContent,/<script>bad<\/script>/);
vm.runInContext(source.slice(source.indexOf('function fillSettings()'),source.indexOf('function fillTaskbarWindows(')),context);
vm.runInContext(source.slice(source.indexOf('function readTaskbarSettings()'),source.indexOf('async function taskbarPreview()')),context);
Object.assign(context.preferences,{RefreshInterval:60,ShowRemaining:true,AutoStart:false,AutoExchangeRate:true,Reminders:{},TaskbarDisplay:{DisplayMode:'overlay',SelectionMode:'default',SelectedWindowKey:'',ShowCost:true,ShowCountdown:true}});
vm.runInContext('fillSettings()',context);
assert.equal($('exchange-auto').checked,true);
assert.equal($('exchange').disabled,true);
assert.equal(vm.runInContext('formPatch().ExchangeRate',context),undefined,'Auto mode must not resubmit a stale displayed rate');
assert.equal(vm.runInContext('formPatch().AutoExchangeRate',context),undefined,'Unchanged automatic mode need not be saved');
$('exchange-auto').checked=false;
assert.equal(vm.runInContext('formPatch().ExchangeRate',context),6.6483,'Switching to manual pins the visible rate even before it is edited');
$('exchange').value='7.25';
vm.runInContext('exchangeInputMode()',context);
assert.equal($('exchange').disabled,false);
const patch=vm.runInContext('formPatch()',context);
assert.equal(patch.AutoExchangeRate,false);
assert.equal(patch.ExchangeRate,7.25);
context.settingsDirty=true;
context.preferences.ExchangeRate=6.7;
vm.runInContext('fillSettings()',context);
assert.equal($('exchange').value,'7.25','Online updates must preserve an unsaved manual rate');
assert.equal($('exchange-auto').checked,false,'Polling must preserve an unsaved mode');
$('exchange-auto').checked=true;
assert.equal(vm.runInContext('formPatch().ExchangeRate',context),undefined,'Restoring automatic mode drops the manual draft from its patch');
assert.match(page,/<button id="rates-refresh" type="button">/);
assert.match(source,/api\('rates\/refresh',\{\}\)/);
assert.match(page,/https:\/\/frankfurter\.dev\//);
assert.match(page,/非逐笔行情/);
console.log('Online exchange-rate states, auto/manual patches and unsaved form preservation tests passed.');
